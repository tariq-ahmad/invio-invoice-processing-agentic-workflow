"""Plain-language summary for the human-approval card.

The reviewer's first read: what the invoice is, why it needs a human, and what
to check before deciding. Generated by a small Gemini model from the structured
facts the pipeline already holds (extracted fields, validation flags/rubric, PO
match, Agent Memory precedent) — it never sees the PDF and never decides.

Advisory only. A model failure, timeout, or ``ENABLE_REVIEW_SUMMARY=false``
falls back to a deterministic summary built from the same facts, so the card
always has text and the HITL gate is never blocked by the LLM.

The Agent Memory section of the card gets the same treatment
(``generate_memory_summary``): the model rewrites the deterministic precedent tally
as a short note, and the template sentence from app/memory.py is the fallback.
Both calls report their token usage so the card's cost panel counts them.
"""

from __future__ import annotations

import asyncio
import logging
import os
import time
from typing import Any

from google.genai import types as genai_types
from pydantic import BaseModel

from app import memory
from app.models import MODEL_DRAFT_EMAIL

logger = logging.getLogger(__name__)

ENABLED: bool = os.getenv("ENABLE_REVIEW_SUMMARY", "true").strip().lower() in ("1", "true", "yes", "on")
TIMEOUT_S: float = 20.0
_MAX_FLAGS = 12
_MAX_LISTED_FINDINGS = 2  # fallback summary names this many findings, then "+N more"

_INSTRUCTION = (
    "You write the briefing an accounts-payable approver reads FIRST, before deciding whether to "
    "approve or reject an invoice that automated checks held for human review.\n\n"
    "Write it the way a helpful colleague would say it across a desk: warm, plain, conversational "
    "English in the active voice, with contractions where natural (it's, doesn't, wasn't). Avoid "
    "system jargon and report-speak such as 'flagged', 'triggered', 'rule failed', 'validation', "
    "'exceeds threshold' or 'routed'; say what happened in everyday words instead (for example "
    "'this is well over the amount we can approve automatically').\n\n"
    "Return JSON with exactly two fields, each a finished paragraph of 2-3 short sentences "
    "(about 30-40 words, 2-3 lines on screen):\n"
    "- what: who billed what amount, on which invoice and PO, and the main reason it needs a human.\n"
    "- check: what the approver might want to look at in the original document, plus any matched-PO "
    "or vendor-history point that matters.\n\n"
    "Bold the key facts by wrapping them in **double asterisks**: the vendor name, the amount, the "
    "invoice and PO numbers, and the finding. Use 3-6 bold phrases in total, each copied exactly "
    "from the facts. No other markdown, no bullets, no line breaks inside a field.\n\n"
    "Output ONLY the finished paragraphs: no drafting notes, no self-corrections, no commentary. "
    "Do not tell the approver what to decide. Use ONLY the facts provided; never invent amounts, "
    "names, dates or history; say 'not on file' for anything missing."
)

# Phrases that mean the model leaked its own drafting into the answer; such output is
# discarded in favour of the deterministic summary.
_DRAFTING_MARKERS = ("wait,", "let's", "let me", "adjust", "draft", "rewrite", "revise", "hmm")
_MAX_PARAGRAPH_CHARS = 420
_MAX_BOLD_PHRASES = 6


class _Briefing(BaseModel):
    what: str
    check: str


class _MemoryNote(BaseModel):
    text: str


def _clean_paragraph(text: str) -> str:
    """Validate one model paragraph; raises ValueError if it looks malformed."""
    text = (text or "").strip()
    lowered = text.lower()
    if not text or "\n" in text or len(text) > _MAX_PARAGRAPH_CHARS:
        raise ValueError("paragraph empty, multi-line or too long")
    if any(m in lowered for m in _DRAFTING_MARKERS):
        raise ValueError("paragraph contains drafting notes")
    if text.count("**") % 2 or text.count("**") > 2 * _MAX_BOLD_PHRASES:
        raise ValueError("unbalanced or excessive bold markup")
    return text


def _fmt(amount: Any) -> str:
    """'12500.00' / 12500.0 -> '12,500.00'; non-numeric text is returned unchanged."""
    if amount in (None, ""):
        return ""
    try:
        return f"{float(str(amount).replace(',', '')):,.2f}"
    except ValueError:
        return str(amount)


def _val(record: dict, key: str) -> str:
    return str(((record.get(key) or {}).get("value")) or "").strip()


def _facts(
    record: dict,
    flags: list[str],
    rubric: list[dict],
    po_match: dict | None,
    precedent: dict | None,
    threshold_usd: float | None,
) -> str:
    lines = [
        f"Vendor: {_val(record, 'vendor') or 'not on file'}",
        f"Invoice no: {_val(record, 'invoice_no') or 'not on file'}",
        f"PO reference: {_val(record, 'po_ref') or 'not on file'}",
        f"Total: {_val(record, 'currency') or 'USD'} {_fmt(_val(record, 'total')) or 'not on file'}",
    ]
    if threshold_usd:
        lines.append(f"Auto-approval limit: USD {threshold_usd:,.0f}")
    items = record.get("line_items") or []
    if items:
        lines.append("Line items:")
        lines += [f"  - {li.get('name') or '?'}: {_fmt(li.get('amount')) or '?'}" for li in items[:15]]
    lines.append("Findings raised by the checks:")
    lines += [f"  - {f}" for f in flags[:_MAX_FLAGS]] or ["  - (none recorded)"]
    passed = [r.get("label") for r in rubric if isinstance(r, dict) and r.get("status") == "pass"]
    if passed:
        lines.append("Checks that passed: " + "; ".join(str(p) for p in passed))
    if po_match and po_match.get("matched"):
        lines.append(
            "Matched PO: {po} · vendor {vendor} · {cur} {amt} · status {status}".format(
                po=po_match.get("po_number") or "?",
                vendor=po_match.get("vendor_name") or "?",
                cur=po_match.get("currency") or "USD",
                amt=_fmt(po_match.get("po_amount")) or "?",
                status=po_match.get("po_status") or "?",
            )
        )
    elif po_match:
        lines.append("Matched PO: none found in the PO ledger")
    if precedent and precedent.get("total_count") and precedent.get("narrative"):
        lines.append(f"Vendor history: {precedent['narrative']}")
    return "\n".join(lines)


def fallback_summary(record: dict, flags: list[str], po_match: dict | None = None) -> str:
    """Deterministic two-paragraph summary used when the model is unavailable."""
    vendor = _val(record, "vendor") or "An unidentified vendor"
    inv = _val(record, "invoice_no")
    po = _val(record, "po_ref")
    amount = f"{_val(record, 'currency') or 'USD'} {_fmt(_val(record, 'total')) or 'unknown'}".strip()
    what = f"**{vendor}** sent an invoice for **{amount}**"
    what += f" (**{inv}**)" if inv else ""
    what += f", billed against PO **{po}**." if po else " and it doesn't mention a PO."
    if flags:
        # Name up to two findings in full; anything beyond that is just counted.
        listed = [f.split(". ")[0].rstrip(".") for f in flags[:_MAX_LISTED_FINDINGS]]
        what += f" It needs a person to take a look because: {'; '.join(listed)}."
        extra = len(flags) - len(listed)
        if extra > 0:
            what += f" (+{extra} more finding{'s' if extra > 1 else ''}.)"
    else:
        what += " Nothing specific went wrong, but it was sent to you for a manual check."
    if po_match and po_match.get("matched"):
        check = (
            f"It's worth comparing the figures with the original document and PO "
            f"**{po_match.get('po_number') or po}** (currently {po_match.get('po_status') or 'status unknown'})."
        )
    else:
        check = "It's worth comparing the figures with the original document and confirming the PO."
    return f"{what}\n\n{check}"


def _usage(response: Any) -> dict[str, int]:
    """Token usage of one model call (zeros when the response carries none)."""
    u = getattr(response, "usage_metadata", None)
    return {
        "input_tokens": int(getattr(u, "prompt_token_count", 0) or 0),
        "output_tokens": int(getattr(u, "candidates_token_count", 0) or 0),
        "thinking_tokens": int(getattr(u, "thoughts_token_count", 0) or 0),
        "cache_read_tokens": int(getattr(u, "cached_content_token_count", 0) or 0),
    }


async def _call_model(contents: str, instruction: str, schema: type[BaseModel]) -> Any:
    """One small structured-output Gemini call (shared by both card briefings)."""
    import google.genai as genai

    client = genai.Client(
        vertexai=True,
        project=os.environ.get("GOOGLE_CLOUD_PROJECT", ""),
        location=os.environ.get("GOOGLE_CLOUD_LOCATION", "global"),
    )
    return await asyncio.wait_for(
        client.aio.models.generate_content(
            model=MODEL_DRAFT_EMAIL,
            contents=contents,
            config=genai_types.GenerateContentConfig(
                system_instruction=instruction,
                temperature=0.2,
                max_output_tokens=2048,
                # Structured output: the model can only return the finished
                # text, so reasoning/drafting can't leak into the card.
                response_mime_type="application/json",
                response_schema=schema,
                thinking_config=genai_types.ThinkingConfig(thinking_level=genai_types.ThinkingLevel.LOW),
            ),
        ),
        timeout=TIMEOUT_S,
    )


async def generate_review_summary(
    record: dict,
    flags: list[str],
    rubric: list[dict] | None = None,
    po_match: dict | None = None,
    precedent: dict | None = None,
    threshold_usd: float | None = None,
) -> dict[str, Any]:
    """Return ``{text, source, model, latency_ms}``; never raises."""
    fallback = {
        "text": fallback_summary(record, flags, po_match),
        "source": "fallback",
        "model": None,
        "latency_ms": None,
    }
    if not ENABLED:
        return fallback

    t0 = time.perf_counter()
    try:
        response = await _call_model(
            _facts(record, flags, rubric or [], po_match, precedent, threshold_usd), _INSTRUCTION, _Briefing
        )
        briefing = _Briefing.model_validate_json(response.text or "")
        text = f"{_clean_paragraph(briefing.what)}\n\n{_clean_paragraph(briefing.check)}"
        return {
            "text": text,
            "source": "llm",
            "model": MODEL_DRAFT_EMAIL,
            "latency_ms": round((time.perf_counter() - t0) * 1000.0),
            **_usage(response),
        }
    except Exception as exc:  # advisory: never block the gate
        logger.warning("review summary fell back to deterministic text: %s", exc)
        return fallback


