_MEMORY_INSTRUCTION = (
    "You write the Agent Memory note an accounts-payable approver reads on an approval card. "
    "Agent Memory holds earlier human approve/reject decisions for the same vendor and the same kind "
    "of finding.\n\n"
    "Return JSON with exactly one field, text: a finished paragraph of 2-3 short sentences (about "
    "35-50 words). Say what the earlier decisions were (how many, and the amounts when given), how "
    "this invoice compares ONLY where the figures make it plainly true, and, if Agent Memory gives a "
    "recommendation, state it and that it is advisory.\n\n"
    "Bold the key facts by wrapping them in **double asterisks**: the vendor name, the counts, the "
    "amounts and the recommendation. Use 3-5 bold phrases in total, each copied exactly from the facts. "
    "No other markdown, no bullets, no line breaks.\n\n"
    "Output ONLY the finished paragraph. Do not tell the approver what to decide. Use ONLY the facts "
    "provided; never invent amounts, names, dates or history."
)


def _memory_facts(
    precedent: dict, record: dict, flags: list[str], threshold_usd: float | None
) -> str:
    kinds = precedent.get("flag_kinds") or []
    total = int(precedent.get("total_count") or 0)
    approve = int(precedent.get("approve_count") or 0)
    reject = int(precedent.get("reject_count") or 0)
    lines = [
        "This invoice:",
        f"  Vendor: {_val(record, 'vendor') or 'not on file'}",
        f"  Total: {_val(record, 'currency') or 'USD'} {_fmt(_val(record, 'total')) or 'not on file'}",
    ]
    if threshold_usd:
        lines.append(f"  Auto-approval limit: USD {threshold_usd:,.0f}")
    lines.append("  Findings: " + ("; ".join(flags[:_MAX_FLAGS]) if flags else "(none recorded)"))
    lines += [
        "Agent Memory (earlier human decisions on this vendor with the same kind of finding):",
        f"  Kind of finding matched: {memory._kind_phrase(kinds)}",
        f"  Earlier decisions: {total} in total, {approve} approved, {reject} rejected",
    ]
    if precedent.get("approved_amounts"):
        lines.append("  Approved before at: " + ", ".join(precedent["approved_amounts"]))
    if precedent.get("rejected_amounts"):
        lines.append("  Rejected before at: " + ", ".join(precedent["rejected_amounts"]))
    rec = precedent.get("recommendation")
    lines.append(
        f"  Agent Memory recommendation: {rec} (every earlier decision agreed)"
        if rec
        else "  Agent Memory recommendation: none (history is too thin or mixed to steer)"
    )
    return "\n".join(lines)


def _clean_memory_note(text: str, recommendation: str | None) -> str:
    text = _clean_paragraph(text)
    # The recommendation comes from a fixed tally rule, never from the model: if
    # there is one, the note must carry it, so a dropped or altered one is rejected.
    if recommendation and recommendation.lower() not in text.lower():
        raise ValueError("memory note omits the recommendation")
    return text


async def generate_memory_summary(
    precedent: dict,
    record: dict,
    flags: list[str],
    threshold_usd: float | None = None,
) -> dict[str, Any]:
    """Return ``{text, source, model, latency_ms, ...tokens}``; never raises.

    ``precedent`` is the ``decision_precedents`` state (app/memory.py
    PrecedentSummary). The fallback is that summary's own template sentence.
    """
    fallback = {
        "text": precedent.get("narrative") or "",
        "source": "fallback",
        "model": None,
        "latency_ms": None,
    }
    if not ENABLED:
        return fallback

    t0 = time.perf_counter()
    try:
        response = await _call_model(
            _memory_facts(precedent, record, flags, threshold_usd), _MEMORY_INSTRUCTION, _MemoryNote
        )
        note = _MemoryNote.model_validate_json(response.text or "")
        return {
            "text": _clean_memory_note(note.text, precedent.get("recommendation")),
            "source": "llm",
            "model": MODEL_DRAFT_EMAIL,
            "latency_ms": round((time.perf_counter() - t0) * 1000.0),
            **_usage(response),
        }
    except Exception as exc:  # advisory: never block the gate
        logger.warning("memory summary fell back to the template sentence: %s", exc)
        return fallback
